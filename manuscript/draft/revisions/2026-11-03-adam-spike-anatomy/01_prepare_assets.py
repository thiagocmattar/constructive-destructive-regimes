"""Copy four approved Adam figures and generate the grouped spike-anatomy table."""
import hashlib
import json
from pathlib import Path
import shutil
import statistics

import numpy as np
import pandas as pd
from scipy.stats import linregress

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
DRAFT = HERE.parents[1]
A36 = ROOT / 'analyses/036-2026-11-02-controlled-adam-diagnostics'
RUN = ROOT / 'runs/215-2026-11-02-controlled-full-batch-adam'
TASKS = ['mlp', 'resnet', 'transformer']
FIGURES = ['adam_manuscript_overview.pdf', 'adam_manuscript_spikes.pdf',
           'adam_peak_increase_density.pdf', 'adam_rho_gradient_rise_peak_scatter.pdf']
METRICS = ['peak_change_percent', 'rise_steps', 'recovery_steps',
    'eta_kappa_hat_raw_before', 'eta_kappa_hat_raw_recovery_mean',
    'rho_raw_before', 'rho_raw_recovery_mean', 'gradient_rise_ratio', 'gradient_recovery_ratio']


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def read(path):
    return json.loads(Path(path).read_text(encoding='utf-8'))


def main():
    anatomy = read(A36 / 'spike_anatomy/manifest.json')
    assert anatomy['status'] == 'passed'
    sources = {}
    for name, digest in anatomy['sources'].items():
        assert sha(ROOT / name) == digest, name
        sources[name] = digest
    for name, digest in anatomy['outputs'].items():
        assert sha(ROOT / name) == digest, name
    events = pd.read_csv(A36 / 'spike_anatomy/events_gt10.csv', float_precision='round_trip')
    full = pd.read_csv(A36 / 'spike_dataset/loss_spikes.csv', float_precision='round_trip')
    selected = full.loc[full.peak_change_percent.gt(10) & full.recovery_state.notna()]
    assert set(events.spike_id) == set(selected.spike_id) and len(events) == 129
    assert len(full.loc[full.recovery_state.notna()]) == 806
    raw = {}
    recovered_boundaries = []
    for arm in read(RUN / 'results.json')['conditions']:
        folder = ROOT / arm['source']
        paths = [folder / 'boundaries.jsonl', folder / 'metrics.jsonl']
        boundaries, metrics = [[json.loads(s) for s in p.read_text().splitlines()] for p in paths]
        for path in paths:
            sources[path.relative_to(ROOT).as_posix()] = sha(path)
        assert len(boundaries) == 1025 and len(metrics) == 1024
        assert [b['state'] for b in boundaries] == list(range(1025))
        assert [m['gradient_state'] for m in metrics] == list(range(1024))
        raw[arm['task'], arm['lr']] = boundaries, metrics
        # Independent first-return segmentation, without an amplitude filter.
        loss = [b['loss'] for b in boundaries]
        a = 0
        while a < 1024:
            if loss[a + 1] <= loss[a]:
                a += 1
                continue
            c = next((s for s in range(a + 1, 1025) if loss[s] <= loss[a]), None)
            if c is None:
                break
            p = max(range(a + 1, c), key=lambda s: loss[s])
            recovered_boundaries.append((arm['task'], arm['lr'], a, p, c))
            a = c
        by_task = events.loc[events.task.eq(arm['task']) & events.learning_rate.eq(arm['lr'])]
        for event in by_task.to_dict('records'):
            a, p, c = (int(event[k]) for k in ['before_state', 'peak_state', 'recovery_state'])
            for field, state in [('loss_before', a), ('loss_peak', p), ('loss_recovery', c)]:
                assert event[field] == loss[state]
            np.testing.assert_allclose(event['gradient_rise_ratio'],
                boundaries[p]['gradient_norm'] / boundaries[a]['gradient_norm'], rtol=1e-12)
            np.testing.assert_allclose(event['gradient_recovery_ratio'],
                boundaries[c]['gradient_norm'] / boundaries[p]['gradient_norm'], rtol=1e-12)
            if a:
                assert event['rho_raw_before'] == metrics[a]['streams']['raw']['cosine']
                assert event['eta_kappa_hat_raw_before'] == boundaries[a]['projected_gradient_change']
            rho = [metrics[s]['streams']['raw']['cosine'] for s in range(p + 1, min(c, 1023) + 1)]
            eta = [boundaries[s]['projected_gradient_change'] for s in range(p + 1, c + 1)]
            np.testing.assert_allclose([event['rho_raw_recovery_mean'], event['eta_kappa_hat_raw_recovery_mean']],
                [statistics.mean(rho), statistics.mean(eta)], rtol=1e-12, atol=1e-14)
    observed = [(e.task, e.learning_rate, int(e.before_state), int(e.peak_state), int(e.recovery_state))
        for e in full.loc[full.recovery_state.notna()].itertuples()]
    assert set(observed) == set(recovered_boundaries) and len(observed) == 806

    summary = pd.read_csv(A36 / 'spike_anatomy/summary_gt10.csv', float_precision='round_trip')
    rows = [r'% Generated by revisions/2026-11-03-adam-spike-anatomy/01_prepare_assets.py.',
        r'\begin{tabular}{@{}lrr*{10}{r}@{}}', r'\toprule',
        r'\multirow{2}{*}{Dataset/model} & \multirow{2}{*}{$\eta$} & \multirow{2}{*}{$N$} & \multicolumn{2}{c}{Peak increase (\%)} & \multicolumn{2}{c}{Time (updates)} & \multicolumn{2}{c}{$\eta\widehat\kappa$ (raw)} & \multicolumn{2}{c}{$\rho$ (raw)} & \multicolumn{2}{c}{Gradient norm ratio} \\',
        r'\cmidrule(lr){4-5}\cmidrule(lr){6-7}\cmidrule(lr){8-9}\cmidrule(lr){10-11}\cmidrule(lr){12-13}',
        r' & & & Mean $\pm$ SD & Max & Rise & Recovery & Before & Recovery & Before & Recovery & Rise & Recovery \\',
        r'\midrule']
    table_values = []
    for task, label in zip(TASKS, [r'\shortstack{CIFAR-10\\MLP}', r'\shortstack{CIFAR-10\\ResNet-32}', r'\shortstack{WikiText-2\\Transformer}']):
        rates = [.0001, .0003, .001] if task == 'mlp' else [.0003, .001, .003]
        for index, lr in enumerate(rates):
            group = events.loc[events.task.eq(task) & events.learning_rate.eq(lr)]
            stats = {}
            for metric in METRICS:
                values = group[metric].dropna().tolist()
                stats[metric] = dict(n=len(values), mean=statistics.mean(values) if values else None,
                    std=statistics.stdev(values) if len(values) > 1 else None, max=max(values) if values else None)
                previous = summary.loc[summary.task.eq(task) & summary.learning_rate.eq(lr) & summary.metric.eq(metric)].iloc[0]
                assert int(previous.n) == len(values)
                if values:
                    np.testing.assert_allclose([stats[metric][k] for k in ['mean', 'std', 'max']],
                        [previous[k] for k in ['mean', 'std', 'max']], rtol=1e-12, atol=1e-13)
            def cell(metric, digits=2):
                s = stats[metric]
                return '--' if not s['n'] else f'${s["mean"]:.{digits}f}\\mathord{{\\pm}}{s["std"]:.{digits}f}$'
            cells = [r'\multirow{3}{*}{' + label + '}' if index == 0 else '', f'{lr:g}', str(len(group)),
                cell('peak_change_percent', 1), '--' if group.empty else f'{stats["peak_change_percent"]["max"]:.1f}',
                cell('rise_steps', 1), cell('recovery_steps', 1),
                *[cell(m) for m in METRICS[3:]]]
            assert len(cells) == 13
            rows.append(' & '.join(cells) + r' \\')
            table_values.append(dict(task=task, learning_rate=lr, n=len(group), stats=stats, cells=cells))
        if task != TASKS[-1]:
            rows.append(r'\midrule')
    rows += [r'\bottomrule', r'\end{tabular}']
    table = DRAFT / 'tables/analysis036_spike_anatomy.tex'
    table.write_text('\n'.join(rows) + '\n', encoding='utf-8')

    examples = []
    for task in TASKS:
        group = events.loc[events.task.eq(task)]
        rate = float(group.learning_rate.max())
        group = group.loc[group.learning_rate.eq(rate)]
        event = group.loc[group.peak_change_percent.idxmax()]
        all_at_rate = full.loc[full.task.eq(task) & full.learning_rate.eq(rate) & full.recovery_state.notna()]
        assert event.spike_id == all_at_rate.loc[all_at_rate.peak_change_percent.idxmax()].spike_id
        a, p, c = (int(event[k]) for k in ['before_state', 'peak_state', 'recovery_state'])
        b, m = raw[task, rate]
        first_above = next(s for s in range(a, c + 1) if b[s]['projected_gradient_change'] is not None and b[s]['projected_gradient_change'] > 2)
        examples.append(dict(task=task, lr=rate, before=a, peak=p, recovery=c,
            first_above_10pct=int(event.first_above_10pct_state), first_eta_above_two=first_above,
            gradient_max=int(event.gradient_max_state_full_event), momentum_max=int(event.momentum_max_state_full_event)))
    assert [e['peak'] for e in examples] == [703, 422, 794]
    assert [e['first_above_10pct'] for e in examples] == [697, 418, 790]
    transformer = examples[-1]
    assert [transformer[k] for k in ['before', 'first_eta_above_two', 'gradient_max', 'momentum_max', 'peak']] == [787, 788, 792, 793, 794]
    b, _ = raw['transformer', .003]
    assert f'{100*(b[788]["loss"]/b[787]["loss"]-1):.2f}' == '0.40'
    claims = dict(recovered_events=806, anatomy_events=129,
        excluded_without_recovery=int((full.peak_change_percent.gt(10) & full.recovery_state.isna()).sum()),
        negative_prerise=int(events.rho_raw_before.lt(0).sum()), defined_prerise=int(events.rho_raw_before.notna().sum()),
        eta_above_two_before=int(events.eta_kappa_hat_raw_before.gt(2).sum()),
        norm_grows_to_peak=int(events.gradient_rise_ratio.gt(1).sum()),
        eta_max_before=int(events.eta_max_lead_to_loss_peak.gt(0).sum()),
        eta_max_coincident=int(events.eta_max_lead_to_loss_peak.eq(0).sum()),
        eta_max_after=int(events.eta_max_lead_to_loss_peak.lt(0).sum()), largest_increase=float(events.peak_change_percent.max()))
    assert [claims[k] for k in ['negative_prerise', 'defined_prerise', 'eta_above_two_before',
        'norm_grows_to_peak', 'eta_max_before', 'eta_max_coincident', 'eta_max_after']] == [117, 127, 21, 129, 82, 29, 18]
    fits = read(A36 / 'rho_gradient_rise_peak_scatter_manifest.json')
    for group in fits['groups']:
        if not group['count']:
            continue
        xy = np.asarray(group['coordinates'])
        fit = linregress(xy[:, 0], np.log10(xy[:, 1]))
        np.testing.assert_allclose(fit.rvalue ** 2, group['regression']['r_squared_log10_loss_ratio'], rtol=1e-12)
    for task in TASKS:
        endpoints = [(rate, b[-1]['loss']) for (name, rate), (b, _) in raw.items() if name == task]
        assert max(endpoints)[1] == min(loss for _, loss in endpoints)
    copied = []
    for name in FIGURES:
        source, target = A36 / 'figures' / name, DRAFT / 'figures/analysis036' / name
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(source, target)
        assert sha(source) == sha(target)
        copied.append(dict(source=source.relative_to(ROOT).as_posix(), target=target.relative_to(ROOT).as_posix(), sha256=sha(target)))
    for path in [A36 / 'spike_anatomy/events_gt10.csv', A36 / 'spike_anatomy/summary_gt10.csv',
        A36 / 'spike_anatomy/manifest.json', A36 / 'spike_dataset/loss_spikes.csv',
        A36 / 'loss_overview_manifest.json', A36 / 'peak_density_manifest.json',
        A36 / 'rho_gradient_rise_peak_scatter_manifest.json', A36 / '01_plot_spikes.py']:
        sources[path.relative_to(ROOT).as_posix()] = sha(path)
    record = dict(generator_sha256=sha(__file__), sources=sources, figures=copied,
        table=dict(path=table.relative_to(ROOT).as_posix(), sha256=sha(table), rows=table_values),
        claims=claims, examples=examples, status='scientific_checks_passed',
        checks=['Independent 806-event segmentation', '129 event anchors and phase means checked against raw histories',
            'Independent mean/sample-SD/max table reductions', 'Largest recovered examples at highest LR',
            'Pre-rise counts and timing counts', 'Independent log-response regression R-squared', 'Byte-identical figure copies'])
    (HERE / 'evidence_manifest.json').write_text(json.dumps(record, indent=2, allow_nan=False) + '\n', encoding='utf-8')
    print('Verified four approved figure copies, nine grouped table rows, 806 event boundaries and 129 raw-history anatomy records.')


if __name__ == '__main__':
    main()
