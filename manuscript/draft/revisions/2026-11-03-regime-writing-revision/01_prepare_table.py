"""Recheck frozen Adam evidence and format the author's readable anatomy table."""
import hashlib
import importlib.util
import json
from pathlib import Path
import statistics

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
DRAFT = HERE.parents[1]
PRIOR = HERE.parent / '2026-11-03-adam-spike-anatomy'
SCRATCH = ROOT / 'tmp/pdfs/manuscript-regime-writing-2026-11-03'
A36 = ROOT / 'analyses/036-2026-11-02-controlled-adam-diagnostics'
METRICS = ['peak_change_percent', 'rise_steps', 'recovery_steps',
           'eta_kappa_hat_raw_before', 'eta_kappa_hat_raw_recovery_mean',
           'rho_raw_before', 'rho_raw_recovery_mean',
           'gradient_rise_ratio', 'gradient_recovery_ratio']


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def number(value):
    """Follow the author's explicit magnitude-based rounding examples."""
    digits = 0 if abs(value) >= 10 else 1 if abs(value) >= 1 else 2
    result = f'{value:.{digits}f}'
    return result.lstrip('-') if float(result) == 0 else result


def main():
    # Run the previous raw-history audit into scratch, preserving both reviews.
    spec = importlib.util.spec_from_file_location('adam_audit', PRIOR / '01_prepare_assets.py')
    audit = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(audit)
    audit.HERE = SCRATCH / 'reference/revision'
    audit.DRAFT = SCRATCH / 'reference/draft'
    audit.HERE.mkdir(parents=True, exist_ok=True)
    (audit.DRAFT / 'tables').mkdir(parents=True, exist_ok=True)
    audit.main()
    checked = json.loads((audit.HERE / 'evidence_manifest.json').read_text())
    figures = json.loads((PRIOR / 'evidence_manifest.json').read_text())['figures']
    for figure in figures:
        assert sha(ROOT / figure['source']) == sha(ROOT / figure['target']) == figure['sha256']

    events = pd.read_csv(A36 / 'spike_anatomy/events_gt10.csv', float_precision='round_trip')
    summary = pd.read_csv(A36 / 'spike_anatomy/summary_gt10.csv', float_precision='round_trip')
    lines = [
        r'% Generated by revisions/2026-11-03-regime-writing-revision/01_prepare_table.py.',
        r'\begin{tabular*}{\textwidth}{@{\extracolsep{\fill}}*{13}{c}@{}}',
        r'\toprule',
        r'\multirow{2}{*}{\shortstack{Dataset\\Model}} & \multirow{2}{*}{$\eta$} & \multirow{2}{*}{$N$} & \multicolumn{2}{c}{Peak increase (\%)} & \multicolumn{2}{c}{Time (updates)} & \multicolumn{2}{c}{$\eta\widehat\kappa$ (raw)} & \multicolumn{2}{c}{$\rho$ (raw)} & \multicolumn{2}{c}{Gradient norm ratio} \\',
        r'\cmidrule(lr){4-5}\cmidrule(lr){6-7}\cmidrule(lr){8-9}\cmidrule(lr){10-11}\cmidrule(lr){12-13}',
        r' & & & Mean $\pm$ SD & Max & Rise & Recovery & Before & Recovery & Before & Recovery & Rise & Recovery \\',
        r'\midrule',
    ]
    rows = []
    labels = [('mlp', r'CIFAR-10\\MLP'),
              ('resnet', r'CIFAR-10\\ResNet-32'),
              ('transformer', r'WikiText-2\\Transformer')]
    rate_tex = {.0001: r'$10^{-4}$', .0003: r'$3\times10^{-4}$',
                .001: r'$10^{-3}$', .003: r'$3\times10^{-3}$'}
    for task, label in labels:
        rates = [.0001, .0003, .001] if task == 'mlp' else [.0003, .001, .003]
        for index, rate in enumerate(rates):
            group = events.loc[events.task.eq(task) & events.learning_rate.eq(rate)]
            stats = {}
            for metric in METRICS:
                values = group[metric].dropna().tolist()
                record = dict(n=len(values), mean=statistics.mean(values) if values else None,
                              std=statistics.stdev(values) if len(values) > 1 else None,
                              max=max(values) if values else None)
                source = summary.loc[summary.task.eq(task) & summary.learning_rate.eq(rate) &
                                     summary.metric.eq(metric)].iloc[0]
                assert record['n'] == source.n
                if values:
                    np.testing.assert_allclose([record[k] for k in ['mean', 'std', 'max']],
                                               [source[k] for k in ['mean', 'std', 'max']], rtol=1e-12)
                stats[metric] = record

            def cell(metric):
                s = stats[metric]
                return '--' if s['n'] == 0 else '$' + number(s['mean']) + r'\,\mathord{\pm}\,' + number(s['std']) + '$'

            cells = [r'\multirow{3}{*}{\shortstack{' + label + '}}' if index == 0 else '',
                     rate_tex[rate], str(len(group)), cell('peak_change_percent'),
                     '--' if group.empty else number(stats['peak_change_percent']['max']),
                     *[cell(metric) for metric in METRICS[1:]]]
            assert len(cells) == 13
            lines.append(' & '.join(cells) + r' \\')
            rows.append(dict(task=task, learning_rate=rate, n=len(group), stats=stats, cells=cells))
        if task != 'transformer':
            lines.append(r'\midrule')
    lines += [r'\bottomrule', r'\end{tabular*}']
    target = DRAFT / 'tables/analysis036_spike_anatomy.tex'
    target.write_text('\n'.join(lines)+'\n', encoding='utf-8')
    record = dict(status='scientific_checks_passed', sources=checked['sources'],
                  figures=figures, claims=checked['claims'], examples=checked['examples'],
                  table=dict(path=target.relative_to(ROOT).as_posix(), sha256=sha(target), rows=rows),
                  checks=checked['checks'] + ['Independent table reductions and author-specified rounding'],
                  rounding='abs >=10: integer; 1<=abs<10: one decimal; abs<1: two decimals',
                  generator_sha256=sha(__file__), raw_audit_generator_sha256=sha(PRIOR / '01_prepare_assets.py'))
    (HERE / 'evidence_manifest.json').write_text(json.dumps(record, indent=2, allow_nan=False)+'\n', encoding='utf-8')
    print('Reformatted all nine rows; frozen figures and all Adam source records verified.')


if __name__ == '__main__':
    main()
