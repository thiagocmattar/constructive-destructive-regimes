    manifest={'script_sha256':sha(Path(__file__)),'reduction_sha256':sha(HERE/'results.json'),
        'figure_data_sha256':sha(HERE/'figure_data.csv'),
        'figures':{p.name:{'bytes':p.stat().st_size,'sha256':sha(p)} for p in sorted((HERE/'figures').glob('*.pdf'))}}
