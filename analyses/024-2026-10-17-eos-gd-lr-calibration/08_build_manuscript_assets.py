"""Copy reviewed artwork and generate endpoint and appendix evidence tables."""
import hashlib
import json
import shutil
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
TASKS = ['mlp', 'resnet', 'transformer']
LABELS = {'mlp': 'MLP', 'resnet': 'ResNet-32', 'transformer': 'Transformer'}


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def scientific(value):
    mantissa, exponent = f'{value:.3e}'.split('e')
    return rf'${mantissa}\!\times\!10^{{{int(exponent)}}}$'


def main():
    manifest = json.loads((HERE / 'single_rows_figure_manifest.json').read_text())
    assert manifest['status'] == 'passed', 'Review the source artwork before manuscript use.'
    results = json.loads((HERE / 'results.json').read_text())
    assert results['status'] == 'passed' and results['available'] == 9
    audit = json.loads((HERE / 'section_iv_review_checks.json').read_text())
    assert audit['status'] == 'passed'
    assert audit['script_sha256'] == sha(HERE / '10_review_section_iv.py')
    assert audit['sources']['analyses/024-2026-10-17-eos-gd-lr-calibration/results.json'] == sha(HERE / 'results.json')
    reviewed = {r['run_id']: r for r in audit['runs']}
    assert len(reviewed) == 9
    for r in audit['runs']:
        assert sha(ROOT / r['source']) == r['source_sha256']
    inputs_path = ROOT / 'cache/eos-multitask/inputs.json'
    inputs = json.loads(inputs_path.read_text())
    assert inputs['reference_sources']['data.py']['revision'] == '13acec6d7c78dacd5e1fe9b0b4a325e1d39abc15'
    names = ['loss_log', 'alignment_displacement', 'norms_projected_change', 'rho']
    outputs = []
    destination = ROOT / 'manuscript/draft/figures/analysis024'
    destination.mkdir(parents=True, exist_ok=True)
    for name in names:
        figure = next(f for f in manifest['figures'] if f['name'] == name)
        source = ROOT / figure['pdf']
        assert sha(source) == figure['pdf_sha256']
        target = destination / source.name
        shutil.copyfile(source, target)
        assert sha(target) == sha(source)
        outputs.append(dict(path=target.relative_to(ROOT).as_posix(), sha256=sha(target),
                            source=source.relative_to(ROOT).as_posix()))
    tables = ROOT / 'manuscript/draft/tables'
    tables.mkdir(exist_ok=True)
    def save_table(name, layout, headers, body, sources):
        lines = ['% Generated by Analysis024/08_build_manuscript_assets.py; do not edit numbers.',
                 r'\begin{tabular}{' + layout + '}', r'\toprule', *headers, r'\midrule']
        for i, cells in enumerate(body):
            if i in (3, 6):
                lines.append(r'\midrule')
            lines.append(' & '.join(cells) + r' \\')
        lines += [r'\bottomrule', r'\end{tabular}', '']
        target = tables / name
        target.write_text('\n'.join(lines), encoding='utf-8', newline='\n')
        outputs.append(dict(path=target.relative_to(ROOT).as_posix(), sha256=sha(target), sources=sources))
    ordered = sorted(results['runs'], key=lambda r: (TASKS.index(r['task']), r['lr']))
    assert len(ordered) == 9
    endpoints, temporal, loss_audit, spectra = [], [], [], []
    coverage = {'mlp': 'Full 5,000 images', 'resnet': 'Fixed 5,000-image subset',
                'transformer': 'Fixed 2,500-sequence subset'}
    for r in ordered:
        a = reviewed[r['run_id']]
        assert (r['task'], r['lr']) == (a['task'], a['lr'])
        assert abs(r['final_B_over_A'] - a['final_R']) < 1e-14
        assert abs(a['final_all_pair'] - a['final_lag_one'] - a['final_beyond_lag_one']) < 1e-8
        prefix = [LABELS[r['task']], f'{r["lr"]:g}']
        q = r['late_1000_q_mean']
        qtext = rf'${q * 1e5:.2f}\!\times\!10^{{-5}}$' if q < 1e-4 else (
                rf'${q * 1e4:.2f}\!\times\!10^{{-4}}$' if q < 1e-3 else f'{q:.4f}')
        endpoints.append(prefix + [f'{r["final_loss"]:.4f}', f'{r["late_1000_cosine_mean"]:.4f}',
                         f'{r["final_B_over_A"]:.4f}', qtext, f'{a["final_gradient_sum_displacement"]:.4f}'])
        temporal.append(prefix + [f'{a["final_gradient_sum_path_length"]:.4f}'] +
                        [scientific(a[key]) for key in ['final_lag_one', 'final_beyond_lag_one', 'final_all_pair']])
        sensitivity = a['sign_sensitivity']
        assert [v['relative_threshold'] for v in sensitivity] == [0, 1e-7, 1e-6, 1e-5]
        counts = [f'{v["sign_disagreements"]}/{v["eligible"]}' for v in sensitivity]
        loss_audit.append(prefix + [counts[0], scientific(a['median_scaled_absolute_loss_residual'])] + counts[1:])
        spectra.append(prefix + [coverage[r['task']], f'{r["final_sampled_eta_lambda"]:.4f}'])
    result_source = 'analyses/024-2026-10-17-eos-gd-lr-calibration/results.json'
    audit_source = 'analyses/024-2026-10-17-eos-gd-lr-calibration/section_iv_review_checks.json'
    save_table('analysis024_endpoints.tex', '@{}llrrrrr@{}', [
        r'Model & $\eta$ & $\mathcal{L}(\theta_{3000})$ & $\overline{\rho}_{\mathrm{late}}$ & $R_{3000}$ & $\overline{\eta\widehat\kappa}_{\mathrm{late}}$ & $\|\Delta_{3000}\|$ \\'],
        endpoints, [result_source, audit_source])
    save_table('analysis024_temporal_accounting.tex', '@{}llrrrr@{}', [
        r'Model & $\eta$ & $P_{3000}$ & $I_{3000}^{(1)}$ & $I_{3000}^{(>1)}$ & $I_{3000}$ \\'],
        temporal, [audit_source])
    save_table('analysis024_loss_audit.tex', '@{}llrrrrr@{}', [
        r' & & & & \multicolumn{3}{c}{Opposite signs / eligible transitions at threshold $\tau$} \\',
        r'\cmidrule(l){5-7}',
        r'Model & $\eta$ & No threshold & Median $e_t$ & $10^{-7}$ & $10^{-6}$ & $10^{-5}$ \\'],
        loss_audit, [audit_source])
    save_table('analysis024_spectral_context.tex', '@{}lllr@{}', [
        r'Model & $\eta$ & Hessian objective coverage & $\eta\lambda_{\max,3000}$ \\'],
        spectra, [result_source])
    record = dict(status='passed', script_sha256=sha(__file__),
                  source_results_sha256=sha(HERE / 'results.json'),
                  source_review_audit_sha256=sha(HERE / 'section_iv_review_checks.json'),
                  source_inputs_sha256=sha(inputs_path), reference_sources=inputs['reference_sources'],
                  source_figure_manifest_sha256=sha(HERE / 'single_rows_figure_manifest.json'),
                  outputs=outputs,
                  checks=['All copied PDFs byte-identical to reviewed analysis artwork',
                          'Four tables each cover all nine conditions',
                          'Source metrics hashes match the retained review audit',
                          'Displacement, temporal accounting and loss audit sourced from verified scalars',
                          'All nine spectral endpoints preserved with explicit objective coverage'])
    (HERE / 'manuscript_assets.json').write_text(json.dumps(record, indent=2) + '\n',
                                               encoding='utf-8', newline='\n')
    print(json.dumps({'status': 'passed', 'figure_copies': len(names), 'tables': 4, 'table_rows': 36}))


if __name__ == '__main__':
    main()
