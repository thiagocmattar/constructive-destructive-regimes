"""Copy reviewed Analysis024 artwork and generate its exact endpoint table."""
import hashlib
import json
import shutil
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
TASKS = ['mlp', 'resnet', 'transformer']
LABELS = {'mlp': 'MLP', 'resnet': 'ResNet-32', 'transformer': 'Transformer'}


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def main():
    manifest = json.loads((HERE / 'single_rows_figure_manifest.json').read_text())
    assert manifest['status'] == 'passed', 'Review the source artwork before manuscript use.'
    results = json.loads((HERE / 'results.json').read_text())
    assert results['status'] == 'passed' and results['available'] == 9
    names = ['loss_log', 'alignment_displacement', 'norms_projected_change', 'rho']
    outputs = []
    destination = ROOT / 'manuscript/draft/figures/analysis024'
    destination.mkdir(parents=True, exist_ok=True)
    for name in names:
        figure = next(f for f in manifest['figures'] if f['name'] == name)
        source = ROOT / figure['pdf']
        assert sha(source) == figure['pdf_sha256']
        target = destination / source.name
        shutil.copyfile(source, target)
        assert sha(target) == sha(source)
        outputs.append(dict(path=target.relative_to(ROOT).as_posix(), sha256=sha(target),
                            source=source.relative_to(ROOT).as_posix()))
    table = ROOT / 'manuscript/draft/tables/analysis024_endpoints.tex'
    table.parent.mkdir(exist_ok=True)
    lines = ['% Generated by Analysis024/08_build_manuscript_assets.py; do not edit numbers.',
             r'\begin{tabular}{@{}llrrrrr@{}}', r'\toprule',
             r'Model & $\eta$ & $\mathcal{L}(\theta_{3000})$ & $\overline{\rho}_{\mathrm{late}}$ & $R_{3000}$ & $\overline{\eta\widehat\kappa}_{\mathrm{late}}$ & $\eta\lambda_{\max,3000}$ \\',
             r'\midrule']
    ordered = sorted(results['runs'], key=lambda r: (TASKS.index(r['task']), r['lr']))
    assert len(ordered) == 9
    for i, r in enumerate(ordered):
        if i in (3, 6):
            lines.append(r'\midrule')
        q = r['late_1000_q_mean']
        qtext = rf'${q * 1e5:.2f}\!\times\!10^{{-5}}$' if q < 1e-4 else (
                rf'${q * 1e4:.2f}\!\times\!10^{{-4}}$' if q < 1e-3 else f'{q:.4f}')
        lines.append(f'{LABELS[r["task"]]} & {r["lr"]:g} & {r["final_loss"]:.4f} & '
                     f'{r["late_1000_cosine_mean"]:.4f} & {r["final_B_over_A"]:.4f} & '
                     f'{qtext} & {r["final_sampled_eta_lambda"]:.4f} ' + r'\\')
    lines += [r'\bottomrule', r'\end{tabular}', '']
    table.write_text('\n'.join(lines), encoding='utf-8', newline='\n')
    outputs.append(dict(path=table.relative_to(ROOT).as_posix(), sha256=sha(table),
                        source='analyses/024-2026-10-17-eos-gd-lr-calibration/results.json'))
    record = dict(status='passed', script_sha256=sha(__file__),
                  source_results_sha256=sha(HERE / 'results.json'),
                  source_figure_manifest_sha256=sha(HERE / 'single_rows_figure_manifest.json'),
                  outputs=outputs,
                  checks=['All copied PDFs byte-identical to reviewed analysis artwork',
                          'All nine endpoint rows generated directly from verified results'])
    (HERE / 'manuscript_assets.json').write_text(json.dumps(record, indent=2) + '\n',
                                               encoding='utf-8', newline='\n')
    print(json.dumps({'status': 'passed', 'figure_copies': len(names), 'table_rows': len(ordered)}))


if __name__ == '__main__':
    main()
