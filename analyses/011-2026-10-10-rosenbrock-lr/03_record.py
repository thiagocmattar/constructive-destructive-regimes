"""Record final reductions, PDF integrity and owning-run observations."""
import json
import sys
from pathlib import Path

import fitz
import numpy as np

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT))
from src.controlled.rosenbrock import sha256, write_json


def write_text(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(text.encode("utf-8"))


def main():
    assert json.loads((HERE / "verification.json").read_text())["passed"]
    cohort = json.loads((HERE / "cohort.json").read_text())
    report = {"updates_per_run": 2000, "initial_loss": 24.2, "conditions": [], "raw_storage_bytes": 0}
    for entry in cohort:
        run_dir = ROOT / entry["directory"]
        output = run_dir / "artifacts/attempts/001-local"
        summary = json.loads((output / "summary.json").read_text())
        history = output / "history.npz"
        row = dict(entry, final_loss=summary["final_loss"], final_point=summary["final_point"],
                   final_gradient_norm=summary["final_gradient_norm"],
                   minimum_loss=summary["minimum_observed_loss"], minimum_loss_update=summary["minimum_loss_update"],
                   final_100_updates_meet_threshold=summary["final_100_updates_meet_threshold"],
                   loss_increase_fraction=summary["loss_increase_fraction"], history_sha256=sha256(history), streams={})
        with np.load(history, allow_pickle=False) as result:
            for stream in ("raw", "momentum"):
                stats = summary["streams"][stream]
                row["streams"][stream] = {"A": stats["final_A"], "B": stats["final_B"],
                    "B_over_A": stats["final_B"] / stats["final_A"],
                    "negative_cosine_fraction": stats["negative_cosine_fraction"],
                    "late_median_cosine": stats["late_median_cosine"],
                    "cosine_defined_pairs": int(np.isfinite(result[stream + "_cosine"]).sum()),
                    "norm_updates": len(result[stream + "_norm"])}
        report["conditions"].append(row)
        report["raw_storage_bytes"] += history.stat().st_size
        point = ", ".join(f"{value:.9f}" for value in summary["final_point"])
        observation = f"""# Observation001: 2,000-update no-decay momentum trajectory at LR {entry['lr_label']}

H010, completed locally on 2026-10-10. At the matched finite horizon, final
f={summary['final_loss']:.12g}, point ({point}), post-update gradient norm
{summary['final_gradient_norm']:.12g}. Initial f=24.2. None of the final 100
positions jointly satisfies f<=1e-8 and gradient norm<=1e-4; no convergence
claim follows from the final loss alone.

| Stream | Final A | Final B | Final B/A | Negative adjacent pairs |
| --- | ---: | ---: | ---: | ---: |
| Raw gradient | {row['streams']['raw']['A']:.9g} | {row['streams']['raw']['B']:.9g} | {row['streams']['raw']['B_over_A']:.9g} | {row['streams']['raw']['negative_cosine_fraction']:.6%} |
| Stored momentum | {row['streams']['momentum']['A']:.9g} | {row['streams']['momentum']['B']:.9g} | {row['streams']['momentum']['B_over_A']:.9g} | {row['streams']['momentum']['negative_cosine_fraction']:.6%} |

Exact sources: [frozen config](../config.json), [summary](../artifacts/attempts/001-local/summary.json),
[manifest](../artifacts/attempts/001-local/manifest.json), [inventory](../artifacts/attempts/001-local/inventory.json),
and ignored `artifacts/attempts/001-local/history.npz`, SHA-256 `{row['history_sha256']}`.
[Verification](../verification.json) confirms exact replay, independent PyTorch
optimizer updates, prefix geometry, objective/gradient and sizes/hashes.

Coverage: all 2,001 positions and 2,000 transitions, both coordinates, float64.
All 1,999 adjacent pairs per stream are defined; update 1 has no preceding pair.
No smoothing, thinning, stochastic replicates or confidence intervals. A is
sum of vector norms, B the norm of their prefix sum; the requested ratio is B/A.
All observed A denominators are positive. Momentum is the stored, uncorrected
first moment, distinct from the preconditioned direction and actual update.

The shared [comparison observation](../../../analyses/011-2026-10-10-rosenbrock-lr/observations/001-learning-rate-comparison.md)
owns the single [nine-panel PDF](../../../analyses/011-2026-10-10-rosenbrock-lr/figures/rosenbrock_learning_rates.pdf),
generated by Analysis011 `02_plot.py`. It labels full paths, start, optimum,
final points and level curves, then overlays the exact requested diagnostics.
One deterministic function/start/beta2/horizon supplies no asymptotic, stability,
information-storage or LLM conclusion. LR effects here include different
positions and gradients encountered during the same update budget.
"""
        write_text(run_dir / "observations/001-trajectory-geometry.md", observation)
        write_text(run_dir / "observations/INDEX.md", "# Observations\n\n- [001: Trajectory and geometry](001-trajectory-geometry.md)\n")
        readme = f"""# {entry['run_id']}: Rosenbrock, momentum without decay, LR {entry['lr_label']}

Completed and verified, 2026-10-10. Exactly 2,000 local CPU updates in attempt
`001-local`; final objective {summary['final_loss']:.12g}, point ({point}).
No cloud resources, billing or transfers. This is one of three matched LR
conditions authorized by the user's refinement; [Analysis011](../../analyses/011-2026-10-10-rosenbrock-lr/README.md)
owns the single comparison figure and H010 method.

f(x,y)=(1-x)^2+100(y-x^2)^2, start (-1.2,1), Adam with betas (0.9,0.95),
epsilon 1e-8 outside sqrt, constant LR {entry['lr_label']}, weight decay 0,
zero initial moments, no clipping, exact gradients and float64. Only LR varies.
No data, sampling, batch or experiment seed. [Config](config.json) is frozen.

[Observation001](observations/001-trajectory-geometry.md) records results,
coverage and limitations. [Verification](verification.json) and the compact
[manifest](artifacts/attempts/001-local/manifest.json), [summary](artifacts/attempts/001-local/summary.json),
[final state](artifacts/attempts/001-local/final_state.json) and
[inventory](artifacts/attempts/001-local/inventory.json) preserve provenance.
The exact raw history remains ignored locally, {history.stat().st_size:,} bytes.
Raw gradients, stored first moments, adaptive directions and actual displacements
are captured at every transition. Post-update loss/gradient norms cover all positions.

`01_run.py` calls [the shared implementation](../../src/controlled/rosenbrock.py),
promoted without numerical changes from frozen Run028. Do not overwrite an
executed attempt or change its source/config. Analysis011 `01_verify.py` replays
in memory; `02_plot.py` recreates the PDF; `03_record.py` records these reductions.
No run jointly sustains the declared loss/gradient stationarity thresholds.
"""
        write_text(run_dir / "README.md", readme)
    write_json(HERE / "results.json", report)
    figure_manifest = json.loads((HERE / "figure_manifest.json").read_text())
    for entry in figure_manifest["sources"]:
        run_dir = ROOT / entry["directory"]
        assert sha256(run_dir / "artifacts/attempts/001-local/history.npz") == entry["history_sha256"]
        assert sha256(run_dir / "config.json") == entry["config_sha256"]
    pdf_path = ROOT / figure_manifest["figure"]
    assert sha256(pdf_path) == figure_manifest["sha256"]
    assert sha256(HERE / "02_plot.py") == figure_manifest["script_sha256"]
    with fitz.open(pdf_path) as pdf:
        assert len(pdf) == 1
        page = pdf[0]
        np.testing.assert_allclose([page.rect.width, page.rect.height], [16 * 72, 23 * 72])
        text = page.get_text()
        for label in ("(a)", "(b)", "(c)", "(d)", "(e)", "(f)", "(g)", "(h)", "(i)",
                      "Starting point", "Global optimum", "Final point", "Optimization trajectory"):
            assert label in text, label
        for block in page.get_text("blocks"):
            assert page.rect.contains(fitz.Rect(block[:4])), block[:4]
        preview = page.get_pixmap(matrix=fitz.Matrix(1.2, 1.2), alpha=False)
        preview.save(str(HERE / "scratch/pdf_review.png"))
    write_json(HERE / "figure_verification.json", {"passed": True, "pages": 1, "panels": 9,
        "pdf_sha256": sha256(pdf_path), "physical_dimensions_inches": [16, 23],
        "required_text_present": True, "all_text_within_page": True, "source_and_script_hashes": True,
        "render": "scratch/pdf_review.png", "visual_review": "pending"})
    print(json.dumps({"raw_storage_bytes": report["raw_storage_bytes"], "figure_integrity": "passed"}))


if __name__ == "__main__":
    main()
